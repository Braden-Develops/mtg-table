// One-time (re-runnable) setup: API keys, LiveKit config and a local HTTPS certificate.
//   npm run setup                      -> uses this PC's first LAN address
//   npm run setup -- --host 192.168.0.5 -> pick the address invite links should use
//   npm run setup -- --new-cert         -> regenerate the certificate
import crypto from 'node:crypto';
import fs from 'node:fs';
import selfsigned from 'selfsigned';
import {
  CERT_FILE, CONFIG_FILE, KEY_FILE, LIVEKIT_YAML,
  lanAddresses, readJson, writeJson,
} from './lib.js';

const args = process.argv.slice(2);
const argValue = (name) => {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : undefined;
};

const lan = lanAddresses();
const existing = readJson(CONFIG_FILE, {});
const host = argValue('--host') || existing.host || lan[0] || 'localhost';

const config = {
  apiKey: existing.apiKey || 'mtg' + crypto.randomBytes(6).toString('hex'),
  apiSecret: existing.apiSecret || crypto.randomBytes(32).toString('base64url'),
  host,
  httpsPort: existing.httpsPort || 8443,
  livekitPort: existing.livekitPort || 7880,
  rtcTcpPort: existing.rtcTcpPort || 7881,
  rtcUdpPort: existing.rtcUdpPort || 7882,
  defaultRoom: existing.defaultRoom || 'table',
};
config.publicUrl = argValue('--public-url')
  || (!argValue('--host') && existing.publicUrl)
  || `https://${host}:${config.httpsPort}`;
writeJson(CONFIG_FILE, config);

// LiveKit only listens for signaling on localhost; browsers reach it through
// the HTTPS server's /rtc proxy. Media (UDP/TCP) goes directly to this PC.
fs.writeFileSync(LIVEKIT_YAML, `# Generated by scripts/setup.js - edit data/config.json and re-run setup instead.
port: ${config.livekitPort}
bind_addresses:
  - 127.0.0.1
rtc:
  tcp_port: ${config.rtcTcpPort}
  udp_port: ${config.rtcUdpPort}
  use_external_ip: false
keys:
  ${config.apiKey}: ${config.apiSecret}
room:
  empty_timeout: 300
logging:
  level: info
`);

if (!fs.existsSync(CERT_FILE) || args.includes('--new-cert') || argValue('--host')) {
  const ips = ['127.0.0.1', ...lan, ...(/^\d+\.\d+\.\d+\.\d+$/.test(host) ? [host] : [])];
  const dns = ['localhost', ...(/^\d+\.\d+\.\d+\.\d+$/.test(host) ? [] : [host])];
  const notAfter = new Date();
  notAfter.setFullYear(notAfter.getFullYear() + 1);
  const pems = await selfsigned.generate([{ name: 'commonName', value: 'MTG Table (local)' }], {
    keyType: 'ec',
    algorithm: 'sha256',
    notAfterDate: notAfter,
    extensions: [
      { name: 'basicConstraints', cA: false },
      { name: 'keyUsage', digitalSignature: true, keyEncipherment: true },
      { name: 'extKeyUsage', serverAuth: true },
      {
        name: 'subjectAltName',
        altNames: [
          ...[...new Set(dns)].map((value) => ({ type: 2, value })),
          ...[...new Set(ips)].map((ip) => ({ type: 7, ip })),
        ],
      },
    ],
  });
  fs.writeFileSync(CERT_FILE, pems.cert);
  fs.writeFileSync(KEY_FILE, pems.private);
  console.log('Created a self-signed HTTPS certificate for:', [...new Set([...dns, ...ips])].join(', '));
}

console.log(`
Setup done.
  Site address : ${config.publicUrl}
  LAN addresses: ${lan.join(', ') || '(none found)'}
Next: npm run invite -- <name>   then   npm start
`);
